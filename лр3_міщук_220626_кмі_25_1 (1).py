# Функції для підготовки зображень (з методички)
def squarification(img):
    width, height = img.size
    max_side = max(width, height)
    new_img = Image.new('RGB', (max_side, max_side), (255, 255, 255))
    x = (max_side - width) // 2
    y = (max_side - height) // 2
    new_img.paste(img, (x, y))
    return new_img

def invert_image(img):
    img_array = np.array(img)
    inverted_img_array = 255 - img_array
    inverted_img_array = inverted_img_array.astype('uint8')
    if inverted_img_array.ndim > 2:
        inverted_img_array = inverted_img_array[:, :, 0]
    return Image.fromarray(inverted_img_array)

def image_to_array(img):
    squar_img = squarification(img)
    resized_img = squar_img.resize((28, 28)).convert('L')
    inverted_img = invert_image(resized_img)
    img_array = np.array(inverted_img) / 255.0
    return img_array.reshape(-1, 28, 28, 1)

